-- Order Service schema (TDD §9.5), Oracle flavour. Cross-service ids (customer, product, supplier, warehouse,
-- reservation, payment intent) are plain RAW(16) values with no foreign key: those rows live in other databases.

CREATE SEQUENCE order_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE orders (
    id                RAW(16)       NOT NULL,
    order_number      VARCHAR2(20)  NOT NULL,
    customer_id       RAW(16)       NOT NULL,
    status            VARCHAR2(30)  DEFAULT 'CREATED' NOT NULL,
    currency          CHAR(3)       NOT NULL,
    subtotal          NUMBER(19,4)  NOT NULL,
    discount          NUMBER(19,4)  DEFAULT 0 NOT NULL,
    shipping_fee      NUMBER(19,4)  DEFAULT 0 NOT NULL,
    tax               NUMBER(19,4)  DEFAULT 0 NOT NULL,
    total             NUMBER(19,4)  NOT NULL,
    shipping_address  VARCHAR2(4000) NOT NULL,   -- JSON snapshot
    billing_address   VARCHAR2(4000),            -- JSON snapshot
    payment_intent_id RAW(16),
    idempotency_key   VARCHAR2(80)  NOT NULL,
    placed_at         TIMESTAMP     NOT NULL,
    confirmed_at      TIMESTAMP,
    cancelled_at      TIMESTAMP,
    cancel_reason     VARCHAR2(200),
    version           NUMBER(19)    DEFAULT 0 NOT NULL,
    updated_at        TIMESTAMP     NOT NULL,
    CONSTRAINT pk_orders PRIMARY KEY (id),
    CONSTRAINT uq_orders_number UNIQUE (order_number),
    -- replaying a request with the same key must find the first order, never create a second
    CONSTRAINT uq_orders_idempotency UNIQUE (idempotency_key, customer_id),
    CONSTRAINT ck_orders_status CHECK (status IN ('CREATED','PAYMENT_PENDING','CONFIRMED','PARTIALLY_SHIPPED',
        'SHIPPED','DELIVERED','CANCELLED','RETURNED','FAILED'))
);
CREATE INDEX idx_orders_customer_placed ON orders (customer_id, placed_at DESC);
CREATE INDEX idx_orders_status_placed ON orders (status, placed_at);

CREATE TABLE order_items (
    id                  RAW(16)       NOT NULL,
    order_id            RAW(16)       NOT NULL,
    product_id          RAW(16)       NOT NULL,
    supplier_product_id RAW(16)       NOT NULL,   -- the offer id
    supplier_id         RAW(16)       NOT NULL,
    title_snapshot      VARCHAR2(500) NOT NULL,
    unit_price          NUMBER(19,4)  NOT NULL,
    quantity            NUMBER(10)    NOT NULL CHECK (quantity > 0),
    line_total          NUMBER(19,4)  NOT NULL,
    fulfilment_status   VARCHAR2(30)  DEFAULT 'PENDING' NOT NULL,
    warehouse_id        RAW(16),
    reservation_id      RAW(16),                  -- set once Inventory has reserved the stock
    CONSTRAINT pk_order_items PRIMARY KEY (id),
    CONSTRAINT fk_oi_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT ck_oi_fulfilment CHECK (fulfilment_status IN ('PENDING','RESERVED','PACKED','SHIPPED','DELIVERED',
        'CANCELLED','RETURNED'))
);
CREATE INDEX idx_oi_order ON order_items (order_id);

CREATE TABLE order_status_history (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    RAW(16)       NOT NULL,
    from_status VARCHAR2(30),
    to_status   VARCHAR2(30)  NOT NULL,
    reason      VARCHAR2(200),
    actor       VARCHAR2(80),
    created_at  TIMESTAMP     NOT NULL
);
CREATE INDEX idx_osh_order_time ON order_status_history (order_id, created_at);

-- One checkout saga per order: where it stopped is where a restart resumes.
CREATE TABLE saga_state (
    saga_id       RAW(16)      NOT NULL,
    saga_type     VARCHAR2(40) NOT NULL,         -- CHECKOUT
    order_id      RAW(16)      NOT NULL,
    current_step  VARCHAR2(60) NOT NULL,         -- RESERVE | PAY | DONE | COMPENSATED
    state         VARCHAR2(20) NOT NULL,         -- RUNNING | COMPLETED | FAILED
    last_event_at TIMESTAMP    NOT NULL,
    version       NUMBER(19)   DEFAULT 0 NOT NULL,
    CONSTRAINT pk_saga_state PRIMARY KEY (saga_id),
    CONSTRAINT uq_saga_order UNIQUE (order_id)
);

-- Transactional outbox; a relay to the message bus is not part of this service yet (same as Payment).
CREATE TABLE order_outbox (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_id RAW(16)        NOT NULL,
    event_type   VARCHAR2(60)   NOT NULL,
    payload      VARCHAR2(4000) NOT NULL,
    status       VARCHAR2(20)   DEFAULT 'PENDING' NOT NULL,
    created_at   TIMESTAMP      NOT NULL,
    sent_at      TIMESTAMP
);
CREATE INDEX idx_order_outbox_pending ON order_outbox (status, created_at);
